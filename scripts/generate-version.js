// Regenerated on every build (see package.json "prebuild"/"prestart" scripts).
// Not committed - see .gitignore.
const fs = require('fs');
const path = require('path');
const {execSync} = require('child_process');

const pkg = require('../package.json');

function getCommitHash() {
  try {
    const dirty = execSync('git status --porcelain').toString().trim().length > 0;
    const hash = execSync('git rev-parse --short HEAD').toString().trim();
    return dirty ? `${hash}-dirty` : hash;
  } catch {
    return 'unknown';
  }
}

const content = `// This file is generated by scripts/generate-version.js - do not edit.
export const VERSION = '${pkg.version}';
export const COMMIT_HASH = '${getCommitHash()}';
`;

fs.writeFileSync(path.join(__dirname, '../src/environments/version.ts'), content);
