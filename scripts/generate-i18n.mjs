import {readdirSync, readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import path from 'node:path';
import MessageFormat from '@messageformat/core';
import {parse} from '@messageformat/parser';

export function readLanguagePacks(directory) {
  const packs = readdirSync(directory).filter(name => name.endsWith('.json')).sort().map(file => ({file, pack: JSON.parse(readFileSync(path.join(directory, file), 'utf8'))}));
  const english = packs.find(({pack}) => pack.meta?.code === 'en')?.pack;
  if (!english) throw new Error('English language pack is required.');
  const signature = value => {
    const names = new Set();
    function visit(tokens) {for (const token of tokens) {if (token.arg) names.add(token.arg); for (const branch of token.cases ?? []) visit(branch.tokens);}}
    visit(parse(value)); return [...names].sort().join(',');
  };
  const codes = new Set();
  for (const {file, pack} of packs) {
    const {code, nativeName, locale, direction, firstDayOfWeek} = pack.meta ?? {};
    if (typeof code !== 'string' || !/^[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*$/.test(code) || file !== `${code}.json` || codes.has(code) || !nativeName?.trim() || !['ltr', 'rtl'].includes(direction) || !Number.isInteger(firstDayOfWeek) || firstDayOfWeek < 0 || firstDayOfWeek > 6) throw new Error(`Invalid language metadata: ${file}`);
    if (Intl.getCanonicalLocales(locale)[0] !== locale || !Intl.NumberFormat.supportedLocalesOf([locale]).length) throw new Error(`Invalid locale: ${file}`);
    codes.add(code);
    const input = pack.input;
    const words = value => Array.isArray(value) && value.length > 0 && value.every(word => typeof word === 'string' && word.trim());
    if (!input?.countWords || Array.isArray(input.countWords) || !Object.keys(input.countWords).length ||
        Object.keys(input.countWords).some(word => !word.trim()) ||
        !words(input.uncertainPrefixes) || !words(input.pieceWords) ||
        !Array.isArray(input.nameSuffixes) || !input.nameSuffixes.every(rule =>
          typeof rule.suffix === 'string' && rule.suffix.trim() && typeof rule.replacement === 'string')) {
      throw new Error(`Missing or invalid input vocabulary: ${file}`);
    }
    if (Object.values(pack.input.countWords).some(value => !Number.isSafeInteger(value) || value < 1 || value > 999)) throw new Error(`Invalid count vocabulary: ${file}`);
    if (Object.keys(pack.messages).sort().join('|') !== Object.keys(english.messages).sort().join('|')) throw new Error(`Translation keys do not match English: ${file}`);
    const compiler = new MessageFormat(locale);
    for (const [key, value] of Object.entries(pack.messages)) {
      if (typeof value !== 'string' || !value.trim()) throw new Error(`Empty translation: ${file} ${key}`);
      compiler.compile(value);
      if (signature(value) !== signature(english.messages[key])) throw new Error(`Translation parameters do not match: ${file} ${key}`);
    }
  }
  return packs;
}

export function generate(directory = 'src/assets/i18n', output = 'src/app/i18n/languages.generated.ts') {
  const packs = readLanguagePacks(directory);
  const imports = packs.map(({file}, i) => `import pack${i} from '../../assets/i18n/${file}';`).join('\n');
  const source = `// Generated by scripts/generate-i18n.mjs. Do not edit.\nimport {LanguagePack} from './language-pack';\n${imports}\nexport const languagePacks: LanguagePack[] = [${packs.map((_, i) => `pack${i} as LanguagePack`).join(', ')}];\n`;
  mkdirSync(path.dirname(output), {recursive: true});
  if (!process.argv.includes('--check')) writeFileSync(output, source);
  return packs;
}
if (process.argv[1] && import.meta.url === new URL(process.argv[1], 'file:').href) {
  const packs = generate();
  await validateSources(packs.find(({pack}) => pack.meta.code === 'en').pack);
  console.log(`Validated ${packs.length} language packs.`);
}

/** Catch removed keys and untranslated visible template text before shipping a language pack. */
export async function validateSources(english, directory = 'src/app') {
  const {parseTemplate} = await import('@angular/compiler');
  const files = folder => readdirSync(folder, {withFileTypes: true}).flatMap(entry => entry.isDirectory()
    ? files(path.join(folder, entry.name)) : [path.join(folder, entry.name)]);
  for (const file of files(directory).filter(file => /\.(html|ts)$/.test(file) && !/\.spec\.ts$|\.generated\.ts$/.test(file))) {
    const source = readFileSync(file, 'utf8');
    for (const match of source.matchAll(/['"]((?:ui|actions|settings|starter|speech|notification|errors|format|catalog|shopping|stock|recipe|step|model|units|date)\.[A-Za-z0-9]+)['"]/g)) {
      if (file.endsWith('.html') && match[0].startsWith('"')) continue;
      if (!(match[1] in english.messages)) throw new Error(`Unknown translation key: ${file} ${match[1]}`);
    }
    if (!file.endsWith('.html')) continue;
    const ast = parseTemplate(source, file, {preserveWhitespaces: true});
    if (ast.errors?.length) throw new Error(`Invalid template: ${file}`);
    function visit(node) {
      if (['Text', 'BoundText'].includes(node.constructor.name)) {
        const text = source.slice(node.sourceSpan.start.offset, node.sourceSpan.end.offset).replace(/{{[\s\S]*?}}/g, '').trim();
        if (/[\p{L}]/u.test(text) && text !== 'Hotties') throw new Error(`Untranslated text: ${file}:${node.sourceSpan.start.line + 1} ${text}`);
      }
      for (const attribute of node.attributes ?? []) {
        if (['aria-label', 'placeholder', 'label', 'title', 'alt', 'cancelText', 'okText', 'doneText'].includes(attribute.name) && /\p{L}/u.test(attribute.value)) {
          throw new Error(`Untranslated attribute: ${file} ${attribute.name}=${attribute.value}`);
        }
      }
      for (const field of ['children', 'branches', 'cases']) for (const child of node[field] ?? []) visit(child);
      if (node.body) visit(node.body);
      if (node.empty) visit(node.empty);
    }
    for (const node of ast.nodes) visit(node);
  }
}
